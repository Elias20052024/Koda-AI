import React from 'react';
import ChatPanel, { type ChatMessage } from '@/components/ai/chat-panel';

const initialMessages: ChatMessage[] = [
  {
    id: 'assistant-welcome',
    role: 'assistant',
    content: 'I can help you discover relevant internships, improve your profile, and keep track of your application progress.',
  },
];

const defaultSuggestions = [
  'Review my dashboard',
  'Find internship matches',
  'Improve my profile',
  'Check my applications',
];

function createMessage(role: 'user' | 'assistant' | 'error', content: string): ChatMessage {
  return {
    id: `${role}-${Date.now()}-${Math.random().toString(16).slice(2)}`,
    role,
    content,
  };
}

export default function AIPage() {
  const [messages, setMessages] = React.useState<ChatMessage[]>(initialMessages);
  const [isLoading, setIsLoading] = React.useState(false);
  const [suggestions, setSuggestions] = React.useState<string[]>(defaultSuggestions);

  const sendMessage = React.useCallback(async (content: string) => {
    const trimmed = content.trim();
    if (!trimmed || isLoading) return;

    const userMessage = createMessage('user', trimmed);
    setMessages((current) => [...current, userMessage]);
    setIsLoading(true);

    try {
      const response = await fetch('/api/ai/chat', {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          ...(typeof window !== 'undefined' && window.localStorage.getItem('koda_auth')
            ? {
                Authorization: `Bearer ${JSON.parse(window.localStorage.getItem('koda_auth') ?? '{}')?.token ?? ''}`,
              }
            : {}),
        },
        body: JSON.stringify({ message: trimmed }),
      });

      let payload: unknown;
      try {
        payload = await response.json();
      } catch {
        throw new Error('The AI service returned an unreadable response. Please try again.');
      }
      const data =
        typeof payload === 'object' && payload !== null
          ? (payload as { reply?: unknown; suggestions?: unknown; error?: unknown })
          : {};

      if (!response.ok) {
        throw new Error(
          typeof data.error === 'string' ? data.error : 'The AI assistant could not complete your request.',
        );
      }

      if (typeof data.reply !== 'string' || !data.reply.trim()) {
        throw new Error('The AI assistant returned an empty response. Please try again.');
      }

      const assistantMessage = createMessage('assistant', data.reply);
      setMessages((current) => [...current, assistantMessage]);
      setSuggestions(
        Array.isArray(data.suggestions) && data.suggestions.every((item) => typeof item === 'string') && data.suggestions.length > 0
          ? data.suggestions
          : defaultSuggestions,
      );
    } catch (error) {
      const errorMessage = createMessage(
        'error',
        error instanceof Error ? error.message : 'Something went wrong. Please try again in a moment.',
      );
      setMessages((current) => [...current, errorMessage]);
    } finally {
      setIsLoading(false);
    }
  }, [isLoading]);

  return (
    <div className="mx-auto max-w-6xl px-4 py-10 md:px-8">
      <div className="mb-8 max-w-2xl">
        <p className="text-xs font-medium uppercase tracking-[0.28em] text-purple-300">AI workspace</p>
        <h1 className="mt-3 text-4xl font-bold tracking-tight text-white">Let your website think with you</h1>
        <p className="mt-3 text-base text-slate-300">
          Ask for internship preparation tips, profile guidance, and career support. Replies are generated by the AI provider configured on the server.
        </p>
      </div>

      <div className="h-[620px]">
        <ChatPanel
          messages={messages}
          isLoading={isLoading}
          onSendMessage={sendMessage}
          suggestions={suggestions}
        />
      </div>
    </div>
  );
}
